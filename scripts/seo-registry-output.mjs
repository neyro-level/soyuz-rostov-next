export function renderSeoRegistryCsv(columns, rows) {
	return `${[
		columns.join(","),
		...rows.map((row) =>
			columns
				.map((column) => {
					const value = row[column];
					return csvCell(
						column === "pageKey"
							? JSON.stringify(value)
							: column === "targetPhrases"
								? value.join("|")
								: value,
					);
				})
				.join(","),
		),
	].join("\n")}\n`;
}

export function deterministicSeoRegistryValidationNow(rows) {
	const latestSnapshot = rows
		.map((row) => row.snapshotDate)
		.sort()
		.at(-1);
	if (!latestSnapshot) throw new Error("SEO registry cannot be empty.");
	return `${latestSnapshot}T23:59:59.999Z`;
}

export function renderSeoRegistryModule(
	rows,
	districtRegistry,
	validationNow = "2026-09-24T12:00:00.000Z",
) {
	return `// Generated by pnpm seo:registry:generate. Do not edit manually.\nimport { assertSeoRegistry, type SeoRegistryRow } from "../../core/seo/registry.ts";\nimport { siteProfile } from "../site-profile.ts";\nimport { createProjectUrlGrammar, type ProjectDistrictRouteRegistry } from "../url-grammar.ts";\nimport type { ProjectSeoTemplateKey } from "./templates.ts";\n\nexport const projectDistrictRouteRegistry = ${JSON.stringify(districtRegistry, null, 2)} as const satisfies ProjectDistrictRouteRegistry;\nconst grammar = createProjectUrlGrammar(siteProfile, projectDistrictRouteRegistry);\n\nexport const projectSeoRegistrySeed: readonly SeoRegistryRow<ProjectSeoTemplateKey>[] = ${JSON.stringify(rows, null, 2)} as const;\n\nassertSeoRegistry({ rows: projectSeoRegistrySeed, buildUrl: grammar.buildUrl, now: new Date(${JSON.stringify(validationNow)}) });\n`;
}
